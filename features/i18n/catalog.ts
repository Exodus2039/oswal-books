export const catalogs = { en, hi } as const;

export type Locale = keyof typeof catalogs;

export const LOCALES: readonly Locale[] = ["en", "hi"];

const TEAMS: Record<Locale, Record<string, string>> = {
  en: { india: "India", australia: "Australia" },
  hi: { india: "भारत", australia: "ऑस्ट्रेलिया" },
};

export function teamLabel(locale: Locale, id: string, fallback: string): string {
  return TEAMS[locale][id] ?? fallback;
}

export function sideLabel(locale: Locale, name: string): string {
  const found = Object.entries(TEAMS.en).find(([, label]) => label === name);
  if (!found) return name;
  return TEAMS[locale][found[0]] ?? name;
}

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}
